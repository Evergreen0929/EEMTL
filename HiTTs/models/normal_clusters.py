def gen_random_vector():

    x_tag = np.random.choice([-1, 1])
    y_tag = np.random.choice([-1, 1])

    x = random.random()
    y = random.uniform(0, math.sqrt(1 - x**2))
    z = math.sqrt(1 - x**2 - y**2)

    return [x * x_tag, y * y_tag, z]


