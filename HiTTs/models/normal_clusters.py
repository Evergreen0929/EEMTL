def normal_clu_center(x=None):                                                      # 1 * B * 3 * H * W
    center = PASCAL_NORMAL_CENTER_COORDINATE
    center = center / torch.norm(center, p=2, dim=1, keepdim=True)
    center = center.unsqueeze(1).unsqueeze(-1).unsqueeze(-1)                # CN * 1 * 3 * 1 * 1
    if x != None:
        oh = torch.sum(x.unsqueeze(0) * center.cuda(), dim=2).permute(1, 0, 2, 3)            # B * CN * H * W
        oh_max = torch.max(oh, dim=1, keepdim=True)[0]
        oh_normal = ((oh_max == oh) * (torch.sum(oh, dim=1, keepdim=True) > 0)).to(dtype=torch.uint8)

        return oh_normal, center.permute(1, 0, 2, 3, 4)
    else:
        return center.permute(1, 0, 2, 3, 4)

